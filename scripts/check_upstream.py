#!/usr/bin/env python3
"""Check upstream TimesFM for updates and open a bump PR automatically.

Runs from cron. Compares:
  - latest `timesfm` version on PyPI  vs backend/requirements.txt pin
  - latest GitHub release/tag of google-research/timesfm (changelog notes)
  - lastModified of the HF checkpoint google/timesfm-3.0-pytorch

On a new PyPI version: branch chore/upstream-timesfm-<ver>, bump the pin,
commit, push, and open a PR with `gh`. Merge stays manual by default —
set AUTO_MERGE=1 to let the script merge the PR itself.

Usage:
  python3 scripts/check_upstream.py [--dry-run]
"""

import json
import os
import re
import subprocess
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

REPO_DIR = Path(__file__).resolve().parent.parent
REQ_FILE = REPO_DIR / "backend" / "requirements.txt"
STATE_FILE = REPO_DIR / ".upstream-state.json"
LOG_FILE = REPO_DIR / "logs" / "upstream-cron.log"
UPSTREAM_REPO = "google-research/timesfm"
HF_MODEL = "google/timesfm-3.0-pytorch"
AUTO_MERGE = os.environ.get("AUTO_MERGE", "0") == "1"
DRY_RUN = "--dry-run" in sys.argv


def log(msg: str) -> None:
    line = f"[{datetime.now(timezone.utc).isoformat(timespec='seconds')}] {msg}"
    print(line, flush=True)
    try:
        LOG_FILE.parent.mkdir(exist_ok=True)
        with LOG_FILE.open("a") as f:
            f.write(line + "\n")
    except OSError:
        pass


def http_json(url: str):
    req = urllib.request.Request(url, headers={"User-Agent": "superbrains-upstream-bot"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read())


def sh(cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=REPO_DIR, capture_output=True, text=True, check=check)


def current_pin() -> str | None:
    m = re.search(r"^timesfm\[torch\]==([\w.\-]+)", REQ_FILE.read_text(), re.M)
    return m.group(1) if m else None


def set_pin(version: str) -> None:
    text = REQ_FILE.read_text()
    text = re.sub(r"^(timesfm\[torch\]==)[\w.\-]+", rf"\g<1>{version}", text, flags=re.M)
    REQ_FILE.write_text(text)


def latest_pypi_version() -> str:
    return http_json("https://pypi.org/pypi/timesfm/json")["info"]["version"]


def upstream_release_notes() -> str:
    try:
        rel = http_json(f"https://api.github.com/repos/{UPSTREAM_REPO}/releases/latest")
        body = (rel.get("body") or "").strip()
        return f"**{rel.get('tag_name', '')}**\n\n{body[:3000]}"
    except Exception:
        try:
            tags = http_json(f"https://api.github.com/repos/{UPSTREAM_REPO}/tags?per_page=3")
            return "Latest upstream tags: " + ", ".join(t["name"] for t in tags)
        except Exception:
            return "_(could not fetch upstream release notes)_"


def hf_model_info() -> dict:
    try:
        info = http_json(f"https://huggingface.co/api/models/{HF_MODEL}")
        return {"lastModified": info.get("lastModified"), "sha": info.get("sha")}
    except Exception as e:
        return {"error": str(e)}


def load_state() -> dict:
    if STATE_FILE.exists():
        try:
            return json.loads(STATE_FILE.read_text())
        except Exception:
            pass
    return {}


def save_state(state: dict) -> None:
    STATE_FILE.write_text(json.dumps(state, indent=2) + "\n")


def git(*args: str) -> None:
    r = sh(["git", *args])
    if r.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {r.stderr.strip()}")


def open_bump_pr(new_version: str, notes: str) -> None:
    branch = f"chore/upstream-timesfm-{new_version}"
    git("checkout", "-B", branch)
    git("add", "backend/requirements.txt", ".upstream-state.json")
    git("-c", "user.name=superbrains-bot",
        "-c", "user.email=bot@superbrains.dev",
        "commit", "-m", f"chore: bump timesfm to {new_version} (upstream sync)")
    git("push", "-u", "origin", branch)

    body = f"""## Upstream sync

Automated bump of `timesfm` after a new release upstream.

- PyPI: `{new_version}` (was `{current_pin()}`)
- Upstream: https://github.com/{UPSTREAM_REPO}

### Upstream notes
{notes}

Generated by `scripts/check_upstream.py`.
"""
    r = sh(["gh", "pr", "create", "--title", f"chore: bump timesfm → {new_version}",
            "--body", body, "--head", branch, "--base", "main"])
    if r.returncode != 0:
        log(f"PR create failed: {r.stderr.strip()}")
        return
    log(f"opened PR: {r.stdout.strip()}")

    if AUTO_MERGE:
        m = sh(["gh", "pr", "merge", "--merge", "--delete-branch"])
        log(f"auto-merge: {m.stdout.strip() or m.stderr.strip()}")


def main() -> int:
    log("check_upstream start")
    state = load_state()

    pypi_version = latest_pypi_version()
    pinned = current_pin()
    hf = hf_model_info()
    log(f"pypi={pypi_version} pinned={pinned} hf_lastModified={hf.get('lastModified')}")

    state.update({
        "pypi_latest": pypi_version,
        "hf_lastModified": hf.get("lastModified"),
        "hf_sha": hf.get("sha"),
        "checked_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    })

    if DRY_RUN:
        log("dry-run: no changes made")
        save_state(state)
        return 0

    if pinned and pypi_version != pinned:
        log(f"new version detected: {pinned} → {pypi_version}")
        notes = upstream_release_notes()
        set_pin(pypi_version)
        state["pending_bump"] = {"from": pinned, "to": pypi_version}
        save_state(state)
        try:
            open_bump_pr(pypi_version, notes)
            state.pop("pending_bump", None)
        except Exception as e:
            log(f"bump failed: {e}")
        save_state(state)
    else:
        log("no new version — nothing to do")
        save_state(state)
    return 0


if __name__ == "__main__":
    sys.exit(main())
